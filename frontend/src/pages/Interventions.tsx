import { useState } from "react";
import { api, type Action, type Opp } from "../api";
import { aed, cls, fd, pct, rel } from "../format";
import { Chip, Loading, Prob, useApp, useData } from "../ui";
import DraftModal from "../components/DraftModal";

export default function Interventions() {
  const { openOpp } = useApp();
  const opps = useData(() => api.get<Opp[]>("/api/opportunities?include_closed=false"));
  const acts = useData(() => api.get<Action[]>("/api/actions"));
  const [draft, setDraft] = useState<{ id: string; kind: "memo" | "email" } | null>(null);
  if (!opps.data || !acts.data) return <Loading error={opps.error || acts.error} />;
  const open = acts.data.filter((a) => !["Completed", "Cancelled"].includes(a.status || ""));
  const flagged = opps.data.filter((o) => o.intervention === "Yes" || o.escalation || o.actions_blocked > 0 || (o.score.delta_14d ?? 0) <= -0.08)
    .sort((a, b) => b.value! * (1 - b.score.p) - a.value! * (1 - a.score.p));
  const atRisk = flagged.reduce((s, o) => s + (o.value || 0) * (1 - o.score.p), 0);
  return (
    <>
      <section className="kpis">
        <div className="kpi alert"><span className="lab">Flagged for intervention</span><span className="val">{flagged.length}</span><span className="sub">Intervention, escalation, blocked or falling fast</span></div>
        <div className="kpi"><span className="lab">Value at risk</span><span className="val"><small>AED</small>{aed(atRisk, false)}</span><span className="sub">Σ value × (1 − p) on flagged deals</span></div>
        <div className="kpi"><span className="lab">Blocked actions</span><span className="val">{open.filter((a) => a.status === "Blocked").length}</span><span className="sub">{open.filter((a) => a.escalate === "Yes").length} with escalation requested</span></div>
        <div className="kpi"><span className="lab">Overdue actions</span><span className="val">{open.filter((a) => rel(a.due).includes("overdue")).length}</span><span className="sub">Across the active register</span></div>
      </section>
      <section className="panel">
        <div className="ph"><h2>Intervention queue</h2><span className="hint">Ordered by value at risk. Drafts are generated by the local model from the record, actions and Engagement Log.</span></div>
        <div className="list">
          {flagged.map((o) => {
            const blockers = open.filter((a) => a.opp === o.id && (a.status === "Blocked" || a.escalate === "Yes"));
            return (
              <div key={o.id} className="li" style={{ gridTemplateColumns: "4px minmax(0,1fr) auto", cursor: "default" }}>
                <span className={cls("sev", (o.intervention === "Yes" || o.score.p < 0.3) && "hi")} />
                <div>
                  <button className="btn ghost" style={{ padding: 0, fontWeight: 600 }} onClick={() => openOpp(o.id)}>{o.name}</button>
                  <div className="hint">{o.id} · {o.country} · {o.status} · Sponsor: {o.sponsor}</div>
                  <div className="chips" style={{ marginTop: 6 }}>
                    {o.intervention === "Yes" && <Chip tone="neg">Intervention required</Chip>}
                    {o.escalation && <Chip tone="neg">Escalation requested</Chip>}
                    {(o.score.delta_14d ?? 0) <= -0.08 && <Chip tone="neg">p {Math.round((o.score.delta_14d || 0) * 100)} pts / 14d</Chip>}
                    {blockers.map((b) => <Chip key={b.id} tone="neu">{b.title}{b.blocker ? `: ${b.blocker}` : ""} · {fd(b.due, false)}</Chip>)}
                  </div>
                  <div className="filters" style={{ marginTop: 8 }}>
                    <button className="btn sm primary" onClick={() => setDraft({ id: o.id, kind: "memo" })}>Draft briefing memo</button>
                    <button className="btn sm" onClick={() => setDraft({ id: o.id, kind: "email" })}>Draft sponsor email</button>
                  </div>
                </div>
                <div className="r"><Prob p={o.score.p} delta={o.score.delta_14d} /><div className="m">{aed(o.value)} · at risk {aed((o.value || 0) * (1 - o.score.p))}</div><div className="m">EV {pct(o.score.ev / (o.value || 1))} of value</div></div>
              </div>
            );
          })}
          {!flagged.length && <div className="empty">No opportunity currently needs executive intervention.</div>}
        </div>
      </section>
      {draft && <DraftModal title={`${draft.kind === "memo" ? "Intervention briefing" : "Sponsor email"} · ${draft.id}`} path={`/api/opportunities/${draft.id}/draft`}
        body={{ kind: draft.kind }} onClose={() => setDraft(null)} outlookOpp={draft.id} />}
    </>
  );
}
